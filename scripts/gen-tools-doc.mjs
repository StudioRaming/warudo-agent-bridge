// Writes docs/TOOLS.md from src/tools.mjs. `--check` exits 1 when the file is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TOOLS } from '../src/tools.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = path.join(ROOT, 'docs', 'TOOLS.md');

const KIND = {
  read: 'read-only',
  free: 'writes bridge files only',
  lease: 'lease control',
  set: 'changes WARUDO (absolute values, safe to repeat)',
  write: 'changes WARUDO',
  destructive: 'removes or replaces user state',
};

function typeOf(schema) {
  if (!schema) return 'any';
  if (schema.enum) return schema.enum.map((value) => `\`${value}\``).join(' \\| ');
  if (schema.type === 'array') {
    if (schema.minItems === 3 && schema.maxItems === 3 && schema.items && schema.items.type === 'number') return '[x, y, z]';
    return `${typeOf(schema.items)}[]`;
  }
  return schema.type || 'any';
}

function limits(schema) {
  const parts = [];
  if (schema.minimum !== undefined && schema.maximum !== undefined) parts.push(`${schema.minimum}..${schema.maximum}`);
  else if (schema.minimum !== undefined) parts.push(`>= ${schema.minimum}`);
  else if (schema.maximum !== undefined) parts.push(`<= ${schema.maximum}`);
  if (schema.default !== undefined) parts.push(`default ${JSON.stringify(schema.default)}`);
  return parts.length ? ` (${parts.join(', ')})` : '';
}

function render() {
  const lines = [
    '# Tools',
    '',
    '<!-- Generated by `npm run docs:tools` from src/tools.mjs. Do not edit by hand. -->',
    '',
    `${TOOLS.length} tools. Every tool that changes WARUDO needs the write lease; the MCP server takes it for you when no other agent holds it.`,
    '',
    '| Kind | Meaning | Lease |',
    '| --- | --- | --- |',
    ...Object.entries(KIND).map(([kind, meaning]) => `| \`${kind}\` | ${meaning} | ${['write', 'set', 'destructive'].includes(kind) ? 'yes' : 'no'} |`),
    '',
  ];
  const groups = [...new Set(TOOLS.map((tool) => tool.group))];
  lines.push('## Contents', '');
  for (const group of groups) lines.push(`- [${group}](#${group.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')})`);
  lines.push('');
  for (const group of groups) {
    lines.push(`## ${group}`, '');
    lines.push('| Tool | Kind | Summary |', '| --- | --- | --- |');
    for (const tool of TOOLS.filter((entry) => entry.group === group)) {
      lines.push(`| [\`${tool.name}\`](#${tool.name}) | ${tool.kind} | ${tool.title} |`);
    }
    lines.push('');
    for (const tool of TOOLS.filter((entry) => entry.group === group)) {
      lines.push(`### ${tool.name}`, '');
      lines.push(tool.description, '');
      const how = tool.local === 'waitLoaded' ? `${tool.operation}, polled by the MCP server`
        : tool.local === 'uiClick' ? `${tool.operation}, after the MCP server finds the element with ui.list`
          : tool.plan ? `${tool.operation}, with a frame timeline the MCP server builds from the arguments` : tool.operation;
      lines.push(`Kind: \`${tool.kind}\` (${KIND[tool.kind]}). Runtime operation: \`${how}\`.${tool.requires ? ` Needs runtime feature \`${tool.requires}\`.` : ''}${tool.requiresCapture ? ' Also needs runtime feature `capture-tools` when a capture option (maxSize, grid, region, around, ...) is passed.' : ''}`, '');
      const properties = Object.entries(tool.inputSchema.properties || {});
      if (properties.length) {
        const required = new Set(tool.inputSchema.required || []);
        lines.push('| Parameter | Type | Required | Notes |', '| --- | --- | --- | --- |');
        for (const [name, schema] of properties) {
          const notes = `${(schema.description || '').replace(/\|/g, '\\|')}${limits(schema)}`.trim();
          lines.push(`| \`${name}\` | ${typeOf(schema)} | ${required.has(name) ? 'yes' : ''} | ${notes} |`);
        }
        lines.push('');
      } else {
        lines.push('No parameters.', '');
      }
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

const text = render();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
  if (current !== text) {
    process.stderr.write('docs/TOOLS.md is out of date. Run: npm run docs:tools\n');
    process.exit(1);
  }
  process.stdout.write('docs/TOOLS.md is up to date.\n');
} else {
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, text);
  process.stdout.write(`wrote ${path.relative(ROOT, TARGET)} (${TOOLS.length} tools)\n`);
}
